import { toCanonicalAmount } from './payment-amount';

describe('toCanonicalAmount', () => {
  it.each([
    ['125.50', '125.5'],
    ['125.500000000000000000', '125.5'],
    ['100.00', '100'],
    ['100', '100'],
    ['100.000000000000000000', '100'],
    ['0.5', '0.5'],
    ['0.000000000000000001', '0.000000000000000001'],
    ['000.500', '0.5'],
    [
      '999999999999999999.999999999999999999',
      '999999999999999999.999999999999999999',
    ],
  ])('formats %s as %s', (amount, expected) => {
    expect(toCanonicalAmount(amount)).toBe(expected);
  });
});
